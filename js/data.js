  function parseSubjectAndRoom(rawText) {
    if (!rawText || !rawText.trim()) return { subject: "", room: "" };
    const text = rawText.trim();
    const roomRegex = /([ปม]\.?\s*\d+\s*[\/-]\s*\d+|[ปม]\.?\s*\d+\/\d+|[ปม]\.?\s*\d+)/;
    const match = text.match(roomRegex);
    if (match) {
      const room = match[0].trim();
      const subject = text.replace(room, "").trim().replace(/\s+$/, "");
      return { subject: subject || text, room: room };
    }
    return { subject: text, room: "" };
  }

